create table usuarios (
    id         bigint generated by default as identity primary key,
    login      varchar(60)  not null unique,
    senha_hash varchar(100) not null
);

create table clientes (
    id        bigint primary key references usuarios (id) on delete cascade,
    rg        varchar(20)  not null unique,
    cpf       varchar(11)  not null unique,
    nome      varchar(120) not null,
    endereco  varchar(255) not null,
    profissao varchar(80)  not null
);

create table rendimentos (
    id                   bigint generated by default as identity primary key,
    cliente_id           bigint         not null references clientes (id) on delete cascade,
    entidade_empregadora varchar(120)   not null,
    valor                numeric(12, 2) not null check (valor > 0)
);

create index idx_rendimentos_cliente on rendimentos (cliente_id);

create table agentes (
    id   bigint primary key references usuarios (id) on delete cascade,
    nome varchar(120) not null,
    cnpj varchar(14)  not null unique,
    tipo varchar(10)  not null check (tipo in ('EMPRESA', 'BANCO'))
);
