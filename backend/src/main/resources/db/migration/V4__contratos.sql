create table contratos_credito (
    id                bigint generated by default as identity primary key,
    banco_id          bigint         not null references agentes (id),
    valor             numeric(12, 2) not null check (valor > 0),
    taxa_juros_mensal numeric(5, 2)  not null check (taxa_juros_mensal >= 0),
    parcelas          integer        not null check (parcelas > 0)
);

create table contratos_aluguel (
    id                  bigint generated by default as identity primary key,
    pedido_id           bigint      not null unique references pedidos_aluguel (id),
    agente_id           bigint      not null references agentes (id),
    tipo_proprietario   varchar(10) not null check (tipo_proprietario in ('CLIENTE', 'EMPRESA', 'BANCO')),
    proprietario_id     bigint      not null references usuarios (id),
    contrato_credito_id bigint unique references contratos_credito (id),
    assinado_em         timestamp with time zone not null
);

create index idx_contratos_agente on contratos_aluguel (agente_id);
