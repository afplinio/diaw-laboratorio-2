create table pedidos_aluguel (
    id                 bigint generated by default as identity primary key,
    cliente_id         bigint         not null references clientes (id),
    automovel_id       bigint         not null references automoveis (id),
    data_inicio        date           not null,
    data_fim           date           not null,
    valor_proposto     numeric(12, 2) not null check (valor_proposto > 0),
    observacoes        varchar(500),
    status             varchar(20)    not null
        check (status in ('EM_ANALISE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    parecer_financeiro varchar(500),
    avaliador_id       bigint references agentes (id),
    criado_em          timestamp with time zone not null,
    avaliado_em        timestamp with time zone,
    versao             bigint         not null default 0,
    check (data_fim >= data_inicio)
);

create index idx_pedidos_cliente on pedidos_aluguel (cliente_id);
create index idx_pedidos_automovel on pedidos_aluguel (automovel_id);
create index idx_pedidos_status on pedidos_aluguel (status);
